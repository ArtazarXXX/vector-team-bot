// фильтр против попыток запутать бота или писать не по теме
export interface GuardrailCheckResult {
  allowed: boolean;
  reason?: 'PROMPT_INJECTION' | 'OFF_TOPIC';
  redirectMessage?: string;
}

export class GuardrailsService {
  // фразы которыми обычно пытаются сбить роль бота
  private injectionPatterns: RegExp[] = [
    /забудь\s+(все|предыдущ|правил|инструкц)/i,
    /ignore\s+(all\s+)?(previous|prior|above)\s+instructions/i,
    /disregard\s+(all\s+)?(previous|prior)/i,
    /system\s+prompt/i,
    /ты\s+теперь\s+(не|другой|без\s+ограничен|dan|кот|человек)/i,
    /jailbreak/i,
    /dan\s+mode/i,
    /developer\s+mode/i,
    /act\s+as\s+(an?\s+)?unrestricted/i,
    /override\s+system/i,
    /сбрось\s+(роль|контекст|правила)/i,
    /поговори\s+со\s+мной\s+как/i,
    /выведи\s+(свой\s+)?(системный\s+)?промпт/i,
    /print\s+(your\s+)?system\s+prompt/i,
  ];

  // 2. Маркеры явных нецелевых категорий (кулинария, аниме, флуд, читы)
  private offTopicPatterns: RegExp[] = [
    // Кулинария и рецепты (круассаны, шаурма, пироги и т.д.)
    /(рецепт|ингредиент|как\s+приготовить|как\s+сварить|как\s+испечь|круассан|шаурм|борщ|пирог|пицц|печень|торт|жарить\s+|варить\s+мясо)/i,
    
    // Аниме, манга, фанфики
    /(аниме|манга|хентай|вайфу|наруто|геншин|клинок\s+рассекающий|додзинси|тайтл|раннобэ|атака\s+титанов|бродячие\s+псы)/i,
    
    // Игровой флуд и читы
    /(чит\s+на|читы\s+для|чит-код|взлом\s+игры|аимбот|aimbot|скины\s+кс|скины\s+роблокс|бравл\s+старс|майнкрафт\s+крафт)/i,
    
    // Лирический/романтический/развлекательный флуд
    /(расскажи\s+анекдот|спой\s+песню|напиши\s+стих\s+про\s+любовь|гороскоп|гадание|признание\s+в\s+любви|поболтаем\s+о\s+жизни)/i,
    
    // Вредоносная деятельность / хакерство
    /(как\s+взломать|ddos|эксплойт|вирус\s+написать|rat-вирус|кража\s+паролей)/i,
  ];

  public checkQuery(text: string): GuardrailCheckResult {
    const trimmed = text.trim();

    // 1. Проверка на инъекции
    for (const pattern of this.injectionPatterns) {
      if (pattern.test(trimmed)) {
        return {
          allowed: false,
          reason: 'PROMPT_INJECTION',
          redirectMessage:
            `▲ **Система защиты «ВЕКТОР»**\n\n` +
            `Попытка изменения системных инструкций или обхода роли заблокирована.\n\n` +
            `Я — специализированный методический наставник по школьным проектам ФГОС и хакатонам.\n\n` +
            `💡 **Давай вернемся к делу:**\n` +
            `Напиши реальную тему или инженерную задумку твоего проекта, и я помогу структурировать гипотезу, цель и задачи!`,
        };
      }
    }

    // 2. Проверка на оффтопик (кулинария, аниме, читы)
    for (const pattern of this.offTopicPatterns) {
      if (pattern.test(trimmed)) {
        return {
          allowed: false,
          reason: 'OFF_TOPIC',
          redirectMessage:
            `▲ **Методический фокус «ВЕКТОР»**\n\n` +
            `Я создан специально для поддержки проектной деятельности школьников (ФГОС) и подготовки к конкурсам/хакатонам.\n\n` +
            `❌ Вопросы кулинарии, аниме, видеоигр и отвлечённые беседы находятся вне рамок подготовки школьных проектов.\n\n` +
            `💡 **Сфокусируемся на твоей победе:**\n` +
            `Напиши идею проекта (например, по IT, робототехнике, экологии, биологии или физике), и мы за пару минут превратим её в строгий академический паспорт!`,
        };
      }
    }

    return { allowed: true };
  }
}

export const guardrailsService = new GuardrailsService();
